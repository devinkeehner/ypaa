  assert.equal(await page.title(), 'Header navigation QA fixture');
  assert.equal(await page.locator('nextjs-portal').filter({ hasText: /error/i }).count(), 0);
  await expanded(first, false);
  assert.equal(await primary.getByRole('link', { name: 'Child one', exact: true }).count(), 0);
  assert.equal(await primary.getByRole('button').count(), 2, 'Flat and empty groups have no toggle');
  await primary.getByRole('link', { name: 'Parent', exact: true }).click();
  await page.waitForURL(/#parent$/);
  assert.equal(new URL(page.url()).hash, '#parent');
  await expanded(first, false);
  await first.focus(); await first.press('Enter'); await expanded(first, true); await focus(first);
  await first.press('Tab'); await focus(primary.getByRole('link', { name: 'Child one', exact: true }));
  await page.keyboard.press('Escape'); await expanded(first, false); await focus(first);
  await first.press('Space'); await expanded(first, true);
  await first.press('ArrowDown'); await focus(primary.getByRole('link', { name: 'Child one', exact: true }));
  await page.keyboard.press('Escape'); await first.press('ArrowUp'); await focus(primary.getByRole('link', { name: /Warning child/ }));
  assert.equal(await primary.getByRole('link', { name: /External child/ }).getAttribute('target'), '_blank');
  assert.equal(await primary.getByRole('link', { name: /External child/ }).getAttribute('rel'), 'noreferrer');
  assert.equal(await primary.getByRole('link', { name: 'Disabled child' }).count(), 0);
  assert.equal(await primary.getByRole('link', { name: 'Invalid child' }).count(), 0);
  await primary.getByRole('link', { name: /Warning child/ }).click();
  await page.getByRole('dialog', { name: 'You are leaving this site' }).waitFor();
  await page.getByRole('button', { name: 'Stay here', exact: true }).click();
  await focus(primary.getByRole('link', { name: /Warning child/ }));
  await page.keyboard.press('Escape');
  await first.click(); await second.click(); await expanded(first, false); await expanded(second, true);
  await page.getByRole('button', { name: 'Outside control' }).click(); await expanded(second, false);
  await first.click(); await primary.getByRole('link', { name: 'Flat link', exact: true }).focus(); await expanded(first, false);
  await first.click(); await primary.getByRole('link', { name: 'Child one', exact: true }).click();
  await page.waitForURL(/#child-one$/);
  assert.equal(new URL(page.url()).hash, '#child-one'); await expanded(first, false);
  await first.click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await page.screenshot({ path: `${evidence}/desktop.png`, fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true });
  await menu.click();
  const mobile = page.getByRole('navigation', { name: 'Mobile navigation', exact: true });
  const toggle = mobile.getByRole('button', { name: 'Child links for Parent', exact: true });
  await focus(mobile.getByRole('link', { name: 'Parent', exact: true }));
  await toggle.click(); await expanded(toggle, true);
  await mobile.getByRole('link', { name: 'Child one', exact: true }).focus();
  await page.keyboard.press('Escape'); await expanded(toggle, false); await focus(toggle);
  assert.equal(await mobile.isVisible(), true, 'First Escape closes the group only');
  await page.keyboard.press('Escape');
  await focus(page.getByRole('button', { name: 'Open navigation', exact: true }));
  assert.equal(await mobile.count(), 0, 'Second Escape closes the whole mobile menu');
  await menu.click(); await toggle.click();
  await mobile.getByRole('link', { name: /Warning child/ }).click();
  await page.getByRole('button', { name: 'Stay here', exact: true }).click();
