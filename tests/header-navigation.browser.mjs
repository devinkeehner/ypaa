  console.log(JSON.stringify({ status: 'passed', url: base, viewports: ['1440x1000', '390x844', '390x844 touch'], checks: ['identity', 'meaningful content', 'no overlay', 'console clean', 'keyboard', 'focus', 'Escape', 'outside click', 'parent link', 'child navigation', 'warning cancellation', 'new-tab semantics', 'flat fallback', 'invalid and disabled children', 'resize reset', 'light contrast', 'touch tap', 'screenshots'], evidence }, null, 2));
