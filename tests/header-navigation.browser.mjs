  await mobile.getByRole('link', { name: /Warning child/ }).click();
  await page.getByRole('dialog', { name: 'You are leaving this site' }).waitFor();
  await page.keyboard.press('Escape');
  await focus(mobile.getByRole('link', { name: /Warning child/ }));
  assert.equal(await mobile.isVisible(), true, 'Dialog Escape must not close the underlying mobile panel');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await page.screenshot({ path: `${evidence}/mobile.png`, fullPage: false });
  await mobile.getByRole('link', { name: 'Child two', exact: true }).click();
